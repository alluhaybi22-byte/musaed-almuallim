import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import {chromium} from '@playwright/test';
const server=spawn(process.execPath,['scripts/serve.mjs'],{env:{...process.env,PORT:'4201'},stdio:['ignore','pipe','pipe']});
await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('server timeout')),15000);server.stdout.on('data',d=>{if(String(d).includes('http://localhost')){clearTimeout(timer);resolve();}});});
const browser=await chromium.launch({args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:390,height:844}});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const action=a=>page.locator('[data-action="'+a+'"]:visible').first().click();
const readState=()=>page.evaluate(async()=>(await import('/src/storage.js')).readState());
try{
await page.goto('http://localhost:4201');
await page.getByRole('heading',{name:'صفي',exact:true}).waitFor();
await page.evaluate(async()=>{
const storage=await import('/src/storage.js');const state=await storage.readState();
state.students=[{id:'a',name:'طالب أول',grade:2,section:'أ'},{id:'b',name:'طالب ثان',grade:2,section:'أ'},{id:'c',name:'طالب ثالث',grade:2,section:'أ'},{id:'outside',name:'شعبة أخرى',grade:2,section:'ب'}];
await storage.writeState(state);
});
await page.reload();
await page.locator('[data-action="grade"][data-grade="2"]').click();
await page.locator('#section-filter').selectOption('أ');
await action('start-session');
assert.equal(await page.locator('.setup-custom').getAttribute('open'),null);
await page.locator('#setup-lesson').selectOption('g2-u1-l2');
assert.equal(await page.locator('[data-skill]:checked').count(),1);
await action('start-assessment');
const first=await page.locator('.stimulus').innerText();
await page.keyboard.press('1');
await page.locator('.assessment-head h1').filter({hasText:'طالب ثان'}).waitFor();
assert.equal(await page.locator('#report').count(),0);
assert.equal((await readState()).results.length,1);
await action('undo-judgement');
await page.locator('.assessment-head h1').filter({hasText:'طالب أول'}).waitFor();
assert.equal((await readState()).results.length,0);
assert.equal((await readState()).drafts.length,1);
assert.equal(await page.locator('.stimulus').innerText(),first);
await page.keyboard.press('2');
await page.locator('.assessment-head h1').filter({hasText:'طالب ثان'}).waitFor();
assert.notEqual(await page.locator('.stimulus').innerText(),first);
await action('skip-student');
await page.locator('.assessment-head h1').filter({hasText:'طالب ثالث'}).waitFor();
await action('end-session');
await page.locator('#session-sheet').waitFor();
assert((await page.locator('#session-sheet').innerText()).includes('تم تجاوزه'));
await page.locator('#session-sheet tr').filter({hasText:'طالب ثان'}).locator('[data-action="resume"]').click();
await page.keyboard.press('3');
await page.locator('.assessment-head h1').filter({hasText:'طالب ثالث'}).waitFor();
assert.equal((await readState()).drafts.length,1,'reuse existing next-student draft');
await page.keyboard.press('4');
await page.locator('#session-sheet').waitFor();
assert.equal((await readState()).results.length,3);
assert.equal((await readState()).drafts.length,0);
assert(!(await page.locator('#session-sheet').innerText()).includes('شعبة أخرى'));
await action('undo-judgement');
await page.locator('.assessment-head h1').filter({hasText:'طالب ثالث'}).waitFor();
assert.equal((await readState()).results.length,2);
await page.keyboard.press('1');
await page.locator('#session-sheet').waitFor();
await page.reload();
assert.equal(await page.locator('#section-filter').inputValue(),'أ');
assert.equal(await page.locator('.tabs [data-grade="2"]').getAttribute('class'),'active');
await action('start-session');
assert.equal(await page.locator('#setup-lesson').inputValue(),'g2-u1-l2');
assert.equal(await page.locator('[data-skill]:checked').count(),1);
assert.equal(await page.locator('.setup-custom').getAttribute('open'),null);
await page.locator('.nav [data-route="results"]').click();
await action('open-session');
assert((await page.locator('#session-sheet').innerText()).includes('متقدم'));
assert((await page.locator('#session-sheet').innerText()).includes('متمكن'));
assert((await page.locator('#session-sheet').innerText()).includes('متفوق'));
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await mkdir('test-results',{recursive:true});
await page.screenshot({path:'test-results/classroom-session-mobile.png',fullPage:true});
await context.setOffline(true);await page.reload();
await page.getByRole('heading',{name:'صفي',exact:true}).waitFor();
assert.equal((await readState()).results.length,3);
await context.setOffline(false);
assert.deepEqual(errors,[]);
console.log('PASS classroom presets, saved class/section/lesson, automatic next, sentence rotation, undo across students and completion, skip/resume without duplicates, session-specific results, mobile and offline persistence');
}catch(error){await mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/classroom-failure.png',fullPage:true});console.log((await page.locator('body').innerText()).slice(-4000));throw error;}
finally{await browser.close();server.kill();}
