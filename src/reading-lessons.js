export const READING_LEVELS = {
  words: 'كلمات من الدرس',
  sentences: 'جمل من الدرس',
  passages: 'مقاطع من نص الدرس',
};
export const readingLessonsFor = (grade, semester, unit) =>
  READING_LESSONS.filter(
    (lesson) =>
      lesson.grade === grade &&
      lesson.semester === semester &&
      lesson.unit === unit,
  );
export const readingLessonById = (id) =>
  READING_LESSONS.find((lesson) => lesson.id === id);

export function lessonReadingSkills(id) {
  const lesson = readingLessonById(id);
  if (!lesson) return [];
  return Object.entries(READING_LEVELS).map(([readingLevel, label]) => ({
    id: `lesson-${lesson.id}-${readingLevel}`,
    grade: lesson.grade,
    semester: lesson.semester,
    unit: lesson.unit,
    kind: 'lesson-reading',
    title: `قراءة ${label} · ${lesson.title}`,
    domain: readingLevel === 'words' ? 'الكلمات والظواهر' : 'الجمل والنصوص',
    lessonId: lesson.id,
    readingLevel,
    source: {
      book: READING_BOOKS[lesson.semester],
      page: lesson.fragments[0].page,
      edition: '1448',
    },
  }));
}

export function lessonReadingCards(skill) {
  const lesson = readingLessonById(skill.lessonId);
  if (
    !lesson ||
    skill.grade !== lesson.grade ||
    skill.unit !== lesson.unit ||
    skill.semester !== lesson.semester ||
    !Object.hasOwn(READING_LEVELS, skill.readingLevel)
  )
    return [];
  let samples = lesson.fragments;
  if (skill.readingLevel === 'words') {
    const seen = new Set();
    samples = lesson.fragments
      .flatMap((fragment) =>
        fragment.text.split(/\s+/).flatMap((word) => {
          const text = word.replace(/[،؛:.!؟«»()]/g, '');
          const key = text.replace(/[\u064b-\u065f\u0670]/g, '');
          if (
            key.length < 3 ||
            !/^[\u0621-\u064a]+$/.test(key) ||
            seen.has(key)
          )
            return [];
          seen.add(key);
          return [{ text, page: fragment.page }];
        }),
      )
      .slice(0, 8);
  } else if (skill.readingLevel === 'sentences') {
    samples = lesson.fragments
      .flatMap((fragment) =>
        fragment.text
          .split(/(?<=[.!؟])\s+/)
          .filter((text) => text.split(/\s+/).length >= 3)
          .map((text) => ({ text, page: fragment.page })),
      )
      .slice(0, 5);
  }
  return samples.map((sample, index) => ({
    id: `${skill.id}-q${index + 1}`,
    skillId: skill.id,
    skillTitle: skill.title,
    kind: 'lesson-reading',
    domain: skill.domain,
    templateVersion: 1,
    lessonId: lesson.id,
    lessonTitle: lesson.title,
    readingLevel: skill.readingLevel,
    source: {
      book: READING_BOOKS[lesson.semester],
      page: sample.page,
      edition: '1448',
    },
    provenance: `من نص درس «${lesson.title}» · ص ${sample.page}`,
    display: sample.text,
    teacherText: '',
    instruction:
      skill.readingLevel === 'words'
        ? 'اقرأ الكلمة من الدرس.'
        : skill.readingLevel === 'sentences'
          ? 'اقرأ الجملة من الدرس.'
          : 'اقرأ المقطع من الدرس قراءة جهرية.',
    expected:
      'متقن إذا قرأ النص المعروض قراءة صحيحة مستقلة دون تلقين. يُقيَّم الفهم في مهمة مستقلة، ولا تُشترط إجابة عن سؤال لهذا الحكم.',
  }));
}

export function readingCardSourceLabel(card) {
  if (card.kind !== 'lesson-reading') return '';
  const original = lessonReadingSkills(card.lessonId)
    .flatMap(lessonReadingCards)
    .find((x) => x.id === card.id);
  if (!original) return 'نص أضافه المعلم';
  return original.display === card.display
    ? original.provenance
    : `عدّله المعلم من درس «${original.lessonTitle}» · المرجع ص ${original.source.page}`;
}
