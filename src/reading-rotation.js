export const sentenceWordCount = (text) =>
  String(text).trim().split(/\s+/).filter(Boolean).length;

export function startSentenceRotation(cards, studentIndex = 0) {
  const pool = cards.filter((card) => card.readingLevel === 'single');
  if (!pool.length) return { cards };
  if (
    pool.length !== cards.length ||
    new Set(pool.map((c) => c.lessonId)).size !== 1
  )
    throw Error('اختر جملة واحدة لكل طالب وحدها دون مهارات أخرى.');
  if (pool.some((c) => sentenceWordCount(c.display) !== 6))
    throw Error('كل جملة في الاختبار السريع يجب أن تتكون من ست كلمات.');
  const index = Math.max(0, studentIndex) % pool.length;
  return {
    cards: [structuredClone(pool[index])],
    sentenceRotation: { index, pool: structuredClone(pool) },
  };
}
export function advanceSentenceRotation(result) {
  if (!result.sentenceRotation) return { cards: structuredClone(result.cards) };
  const { pool, index } = result.sentenceRotation;
  if (
    !Array.isArray(pool) ||
    !pool.length ||
    pool.length > 100 ||
    !Number.isInteger(index) ||
    index < 0 ||
    index >= pool.length ||
    new Set(pool.map((c) => c?.id)).size !== pool.length ||
    pool.some(
      (c) =>
        c?.kind !== 'lesson-reading' ||
        c.readingLevel !== 'single' ||
        [
          'id',
          'skillId',
          'skillTitle',
          'display',
          'instruction',
          'expected',
          'domain',
          'lessonId',
        ].some((key) => typeof c[key] !== 'string' || !c[key]) ||
        sentenceWordCount(c.display) !== 6 ||
        c.lessonId !== result.cards[0]?.lessonId ||
        !c.source ||
        !Number.isFinite(c.source.page),
    )
  )
    throw Error(
      'تعذر متابعة بنك الجمل المحفوظ؛ ابدأ اختبارًا جديدًا من الدرس.',
    );
  return startSentenceRotation(pool, index + 1);
}
