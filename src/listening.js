export function listeningCards(skill) {
  const p = LISTENING_PASSAGES.find(
    (p) => p.grade === skill.grade && p.unit === skill.unit,
  );
  if (!p) return null; // Preserve the existing bank outside the initial three units.
  return p.questions.map(([facet, question, answer], i) => ({
    id: `${skill.id}-${p.id}-q${i + 1}`,
    skillId: skill.id,
    skillTitle: skill.title,
    domain: skill.domain,
    source: skill.source,
    kind: 'listening',
    templateVersion: 3,
    passageId: p.id,
    passageTitle: p.title,
    audioPath: LISTENING_RECORDINGS[p.id]?.path || '',
    audioText: LISTENING_RECORDINGS[p.id]?.text || '',
    facet,
    display: question,
    instruction:
      'يسأل المعلم شفهيًا بعد الاستماع، دون عرض النص أو السؤال للطالب.',
    teacherText: p.text,
    provenance:
      'نص تدريبي أصلي من مفردات موضوع الوحدة؛ ليس نصًا رسميًا ولا توثيقًا لشخصيات الكتاب.',
    expected: `السؤال: ${question} الإجابة: ${answer}. تقبل الإجابة بالمعنى دون اشتراط جملة كاملة أو ضبط نحوي. متقن إذا أجاب مستقلًا؛ بمساعدة عند التلقين.`,
  }));
}

// One passage is shared by three questions. A text edit must update all of them.
export function applyListeningEdits(cards, edits) {
  const textChanges = new Map();
  for (const c of cards) {
    const text = edits[c.id]?.teacherText;
    if (!c.passageId || text === undefined || text === c.teacherText) continue;
    if (!text.trim()) throw Error('اكتب نص الاستماع.');
    if (textChanges.has(c.passageId) && textChanges.get(c.passageId) !== text)
      throw Error('للمقطع الواحد نصوص مختلفة؛ وحّد النص قبل الحفظ.');
    textChanges.set(c.passageId, text);
  }
  return cards.map((c) => {
    const next = { ...c, ...edits[c.id] };
    if (textChanges.has(c.passageId)) {
      next.teacherText = textChanges.get(c.passageId);
      delete next.audioData;
      delete next.audioPath;
      delete next.audioText;
    }
    return next;
  });
}

export function safeListeningAudio(card) {
  if (card.audioText !== card.teacherText) return '';
  if (
    /^\.\/assets\/listening\/listening-g[123]-u[123]-v1\.mp3$/.test(
      card.audioPath || '',
    ) &&
    !card.audioData
  )
    return card.audioPath;
  const candidate = card.audioData || card.audioPath || '';
  return /^data:audio\/(mpeg|mp3|wav|x-wav|ogg|mp4|webm);base64,[A-Za-z0-9+/=]+$/.test(
    candidate,
  )
    ? candidate
    : '';
}
